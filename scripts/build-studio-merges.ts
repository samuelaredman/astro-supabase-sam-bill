/**
 * Turns the reviewed studio-duplicates.csv into a SQL data migration that merges
 * the studios marked as the same company. Writes a file only — it never touches
 * the database. Review it, then run it in the Supabase SQL Editor.
 *
 * In the CSV's `verdict` column, per row:
 *   keep       — the main studio of its group (one per group that has merges)
 *   same       — the same company: merge it into the group's `keep` row
 *   different  — (or blank) leave it alone
 *
 * Run: npx tsx scripts/build-studio-merges.ts [studio-duplicates.csv] [out.sql]
 * Needs migration 20261031000005_canonical-developers.sql applied first.
 */

import { readFileSync, writeFileSync } from 'node:fs';

const input = process.argv[2] ?? 'studio-duplicates.csv';

function parseCsv(text: string): Record<string, string>[] {
  const rows: string[][] = [];
  let row: string[] = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.some((f) => f !== '')) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  const [header, ...body] = rows;
  return body.map((r) => Object.fromEntries(header.map((h, i) => [h.trim(), (r[i] ?? '').trim()])));
}

const rows = parseCsv(readFileSync(input, 'utf8').replace(/^﻿/, ''));
const errors: string[] = [];

const byGroup = new Map<string, Record<string, string>[]>();
for (const r of rows) {
  const v = r.verdict.toLowerCase();
  if (v && !['keep', 'same', 'different'].includes(v)) {
    errors.push(`group ${r.group}: "${r.name}" has verdict "${r.verdict}" — use keep, same or different`);
  }
  if (!byGroup.has(r.group)) byGroup.set(r.group, []);
  byGroup.get(r.group)!.push({ ...r, verdict: v });
}

// duplicate slug → main slug. A studio can appear in more than one group, so
// its answers have to agree across them.
const mergeInto = new Map<string, string>();
const names = new Map(rows.map((r) => [r.slug, r.name]));
for (const [group, members] of byGroup) {
  const same = members.filter((m) => m.verdict === 'same');
  if (!same.length) continue;
  const keep = members.filter((m) => m.verdict === 'keep');
  if (keep.length !== 1) {
    errors.push(`group ${group}: has "same" rows, so it needs exactly one "keep" (found ${keep.length})`);
    continue;
  }
  for (const m of same) {
    const prior = mergeInto.get(m.slug);
    if (prior && prior !== keep[0].slug) {
      errors.push(`"${m.name}" is "same" in two groups with different keeps (${names.get(prior)} / ${keep[0].name})`);
    }
    mergeInto.set(m.slug, keep[0].slug);
  }
}
for (const [dup, main] of mergeInto) {
  if (mergeInto.has(main)) {
    errors.push(`"${names.get(main)}" is a "keep" but is also marked "same" elsewhere — pick one main studio`);
  }
  if (dup === main) errors.push(`"${names.get(dup)}" is merged into itself`);
}

if (errors.length) {
  console.error(`Not written — fix these in ${input} first:\n  ` + [...new Set(errors)].join('\n  '));
  process.exit(1);
}
if (!mergeInto.size) {
  console.error(`Nothing to merge: no rows in ${input} have verdict "same".`);
  process.exit(1);
}

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const dupSlugs = [...mergeInto.keys()];
const allSlugs = [...new Set([...dupSlugs, ...mergeInto.values()])];
const inList = (slugs: string[]) => slugs.map(lit).join(',\n  ');

const now = new Date();
const stamp = now.toISOString().replace(/\D/g, '').slice(0, 8);
const file = process.argv[3] ?? `supabase/migrations/${stamp}235900_merge-duplicate-studios.sql`;
const backup = `_backup_studio_merge_${stamp}`;

const merges = [...mergeInto]
  .sort(([, a], [, b]) => a.localeCompare(b))
  .map(([dup, main]) =>
    `-- ${names.get(dup)} → ${names.get(main)}\n` +
    `SELECT merge_developer((SELECT id FROM developers WHERE slug = ${lit(dup)}), (SELECT id FROM developers WHERE slug = ${lit(main)}));`)
  .join('\n');

const sql = `-- ─────────────────────────────────────────────────────────────────────────────
--  Merge duplicate studios (data). Generated by scripts/build-studio-merges.ts
--  from the reviewed ${input}: ${mergeInto.size} duplicates into ${new Set(mergeInto.values()).size} main studios.
--
--  Needs 20261031000005_canonical-developers.sql applied first.
--  Safe to re-run: the backup is only taken the first time, and merge_developer()
--  is a no-op for a studio already merged into the same main studio.
--  Every merge runs in one transaction — if any studio is missing, none apply.
--
--  ROLLBACK (puts every link back exactly as it was before the first run):
--    BEGIN;
--    UPDATE developers SET canonical_developer_id = NULL
--      WHERE slug IN (${dupSlugs.map(lit).join(', ')});
--    DELETE FROM game_companies WHERE company_id IN (SELECT id FROM developers WHERE slug IN (${allSlugs.map(lit).join(', ')}));
--    INSERT INTO game_companies (game_id, company_id, role)
--      SELECT game_id, company_id, role FROM ${backup} ON CONFLICT DO NOTHING;
--    COMMIT;
-- ─────────────────────────────────────────────────────────────────────────────

-- Every game link of every studio involved, before anything moves.
CREATE TABLE IF NOT EXISTS ${backup} AS
SELECT gc.game_id, gc.company_id, gc.role
FROM game_companies gc
JOIN developers d ON d.id = gc.company_id
WHERE d.slug IN (
  ${inList(allSlugs)}
);

BEGIN;

${merges}

COMMIT;
`;

writeFileSync(file, sql, 'utf8');
console.log(`${mergeInto.size} merges into ${new Set(mergeInto.values()).size} main studios → ${file}`);
